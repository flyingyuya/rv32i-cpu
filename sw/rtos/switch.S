/*=============================================================================
  switch.S  --  首次任务启动与任务出口
  ---------------------------------------------------------------------------
  与 trap.S 共用同一套上下文帧布局（33 字 = 132 字节）：
      字下标 N -> xN（N=1..31），字下标 32 -> mepc
=============================================================================*/
    .section .text, "ax"

/*----------------------------------------------------------------------------
  任务出口：任务函数返回后由 x1(ra) 跳到这里
----------------------------------------------------------------------------*/
    .globl task_entry_trampoline
task_entry_trampoline:
    call    task_exit
1:  j       1b

/*----------------------------------------------------------------------------
  void rtos_start_asm(int idx)  —— 启动第一个任务（不返回）
    a0 = 目标任务在 g_tcb 中的下标
    sizeof(tcb_t) = 20 字节；本 CPU 无 M 扩展，用移位代替乘法
----------------------------------------------------------------------------*/
    .globl rtos_start_asm
rtos_start_asm:
    slli    t0, a0, 4              /* idx * 16 */
    slli    t1, a0, 2              /* idx * 4  */
    add     t0, t0, t1             /* idx * 20 */
    la      t1, g_tcb
    add     t1, t1, t0
    lw      sp, 0(t1)

    li      t0, 0x80               /* MPIE = 1；mret 后 MIE = 1 */
    csrw    mstatus, t0

    lw      t0, 128(sp)
    csrw    mepc, t0

    lw      x1,    4(sp)
    lw      x3,   12(sp)
    lw      x4,   16(sp)
    lw      x5,   20(sp)
    lw      x6,   24(sp)
    lw      x7,   28(sp)
    lw      x8,   32(sp)
    lw      x9,   36(sp)
    lw      x10,  40(sp)
    lw      x11,  44(sp)
    lw      x12,  48(sp)
    lw      x13,  52(sp)
    lw      x14,  56(sp)
    lw      x15,  60(sp)
    lw      x16,  64(sp)
    lw      x17,  68(sp)
    lw      x18,  72(sp)
    lw      x19,  76(sp)
    lw      x20,  80(sp)
    lw      x21,  84(sp)
    lw      x22,  88(sp)
    lw      x23,  92(sp)
    lw      x24,  96(sp)
    lw      x25, 100(sp)
    lw      x26, 104(sp)
    lw      x27, 108(sp)
    lw      x28, 112(sp)
    lw      x29, 116(sp)
    lw      x30, 120(sp)
    lw      x31, 124(sp)
    addi    sp, sp, 132
    mret
