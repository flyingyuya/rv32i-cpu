# =============================================================
#  test_mem.s  --  RV32I 访存指令测试
#  覆盖: sw lw sb sh lb lh lbu lhu
#  重点验证: 符号扩展 / 零扩展 / 字节与半字对齐写入
# =============================================================
.text

    li   x1, 0x400            # 数据基址

    # ---- 字 ----
    li   x2, 0x12345678
    sw   x2, 0(x1)
    lw   x3, 0(x1)            # 0x12345678

    # ---- 字节读取与扩展 ----
    lb   x4, 0(x1)            # 0x00000078  (120)
    lbu  x5, 0(x1)            # 0x00000078  (120)
    lb   x6, 3(x1)            # 0x00000012  (18)

    # ---- 半字读取与扩展 ----
    lh   x7, 0(x1)            # 0x00005678  (22136)
    lhu  x8, 2(x1)            # 0x00001234  (4660)

    # ---- 字节写入 ----
    li   x9, 0xAB
    sb   x9, 4(x1)
    lbu  x10, 4(x1)           # 0x000000AB
    lb   x11, 4(x1)           # 0xFFFFFFAB  (-85)

    # ---- 半字写入 ----
    li   x12, 0xBEEF
    sh   x12, 8(x1)
    lhu  x13, 8(x1)           # 0x0000BEEF
    lh   x14, 8(x1)           # 0xFFFFBEEF  (负数)

    # ---- 用 -1 覆盖一个字节 ----
    li   x15, -1
    sb   x15, 12(x1)
    lbu  x16, 12(x1)          # 0x000000FF

    # ---- 回读被部分覆盖的字，验证字节使能 ----
    lw   x17, 0(x1)           # 0x12345678 未受影响
    lw   x18, 4(x1)           # 0x000000AB

    ecall
