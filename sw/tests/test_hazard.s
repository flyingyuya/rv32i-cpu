# =============================================================
#  test_hazard.s  --  专门针对五级流水线冒险构造的测试
#
#  覆盖场景：
#    1. 相邻指令 RAW        -> 需要 EX/MEM 前递
#    2. 隔一条指令 RAW      -> 需要 MEM/WB 前递
#    3. 隔两条指令 RAW      -> 需要 WB->ID 旁路（寄存器堆同拍写读）
#    4. load 后立刻使用     -> 需要停顿一拍（load-use 冒险）
#    5. load 后立刻分支     -> 分支操作数依赖 load
#    6. load 后立刻作存储源 -> 存储数据依赖 load
# =============================================================
.text

    li   x1, 1
    li   x2, 2

    # ---- 1. 相邻依赖：EX/MEM 前递 ----
    add  x3, x1, x2          # 3
    add  x4, x3, x1          # 4
    add  x5, x4, x1          # 5

    # ---- 2. 隔一条依赖：MEM/WB 前递 ----
    add  x6, x5, x2          # 7
    li   x7, 0
    add  x8, x6, x7          # 7

    # ---- 3. 隔两条依赖：WB->ID 旁路 ----
    add  x9,  x8, x1         # 8
    li   x10, 0
    li   x11, 0
    add  x12, x9, x10        # 8

    # ---- 4. load-use：载入后立刻使用 ----
    li   x13, 0x400
    li   x14, 0xCAFE
    sw   x14, 0(x13)
    lw   x15, 0(x13)
    add  x16, x15, x1        # 0xCAFF

    # ---- 5. load 后立刻分支 ----
    lw   x17, 0(x13)
    beq  x17, x14, hz_ok
    li   x18, 0xBAD          # 不应执行
hz_ok:

    # ---- 6. load 后立刻作为存储数据 ----
    lw   x19, 0(x13)
    sw   x19, 4(x13)
    lw   x20, 4(x13)         # 0xCAFE

    ecall
